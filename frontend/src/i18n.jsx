const LangCtx = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('edupay-lang') || 'fr');

  useEffect(() => {
    localStorage.setItem('edupay-lang', lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key) => dict[key]?.[lang] ?? dict[key]?.fr ?? key;
  const toggle = () => setLang((l) => (l === 'fr' ? 'en' : 'fr'));

  return <LangCtx.Provider value={{ lang, setLang, toggle, t }}>{children}</LangCtx.Provider>;
}

export const useLang = () => useContext(LangCtx);
